CREATE TABLE inventory_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    category      VARCHAR(40)   NOT NULL,
    quantity      NUMERIC(12,2) NOT NULL,
    unit          VARCHAR(20)   NOT NULL,
    minimum_stock NUMERIC(12,2) NOT NULL,
    purchase_date DATE,
    expiry_date   DATE,
    notes         VARCHAR(500),
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT chk_item_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_item_minimum  CHECK (minimum_stock >= 0)
);

CREATE INDEX idx_item_name     ON inventory_item (name);
CREATE INDEX idx_item_category ON inventory_item (category);
CREATE INDEX idx_item_expiry   ON inventory_item (expiry_date);

CREATE TABLE activity_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       VARCHAR(30)  NOT NULL,
    item_name  VARCHAR(100) NOT NULL,
    details    VARCHAR(255),
    created_at TIMESTAMP    NOT NULL
);

CREATE INDEX idx_activity_created ON activity_log (created_at);
